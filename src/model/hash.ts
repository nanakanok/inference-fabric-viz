// Deterministic hashing and PRNG. Nothing in src/model may use Math.random:
// the same inputs and seed must always produce the same workload and paths.

/** 32-bit FNV-1a over a string. */
export function fnv1a(input: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** Final avalanche mix (murmur3 fmix32). */
export function mix32(x: number): number {
  let h = x >>> 0;
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  return h >>> 0;
}

/** Hash an ordered list of fields together with a seed. */
export function hashFields(seed: number, ...fields: (string | number)[]): number {
  return mix32(fnv1a(fields.join('|')) ^ mix32(seed >>> 0));
}

/** mulberry32 PRNG: returns a function yielding floats in [0, 1). */
export function prng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
